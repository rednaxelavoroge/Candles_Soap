/**
 * Реестр текстов сайта, которые заказчица правит из панели.
 *
 * До этого реестра заголовки, подписи, кнопки и служебные абзацы были зашиты
 * прямо в компоненты. Заказчица видела на сайте фразу, шла в панель, а поля
 * под неё там не было. Теперь у каждого такого текста есть ключ, подпись
 * «где это на сайте» и исходное значение — то самое, что раньше стояло в коде.
 *
 * Как это работает:
 * - `site.json` → поле `texts` хранит только то, что заказчица изменила.
 *   Ключа нет — на сайте исходный текст. Ключ есть — её текст, даже пустой.
 * - Пустая строка значит «не показывать»: заказчица стёрла подпись, значит на
 *   странице её быть не должно. Подставлять своё вместо стёртого нельзя —
 *   на этом уже обжигались (см. handoff, «Мораль на будущее»).
 * - Панель рисует поля прямо по этому списку: добавили запись сюда — поле в
 *   панели появилось само, отдельно верстать ничего не нужно.
 *
 * В тексте могут стоять подстановки в фигурных скобках: {имя}, {сайт},
 * {изделие}. Они заменяются значениями на месте, см. `fillText`.
 */

