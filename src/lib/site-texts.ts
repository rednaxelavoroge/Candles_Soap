const BY_KEY = new Map(SITE_TEXTS.map((entry) => [entry.key, entry]));

export function textEntry(key: string): TextEntry | undefined {
  return BY_KEY.get(key);
}

/**
 * Текст по ключу: то, что сохранила заказчица, иначе исходный.
 * Ключ, которого нет в реестре, — ошибка программиста: падаем на сборке,
 * а не показываем пустоту на сайте.
 */
export function resolveText(overrides: Record<string, string> | undefined, key: string): string {
  const entry = BY_KEY.get(key);
  if (!entry) throw new Error(`Неизвестный текст сайта: ${key}`);
  const own = overrides?.[key];
  return typeof own === "string" ? own : entry.default;
}

/** Подставляет {имя}, {сайт}, {изделие} и прочее из словаря. */
export function fillText(text: string, values: Record<string, string>): string {
  return text.replace(/\{([^{}]+)\}/g, (whole, name: string) => values[name.trim()] ?? whole);
}

/**
 * Оставляет в словаре только то, что отличается от исходного: ключ с исходным
 * значением в данных не нужен, а пустая строка — осмысленное «не показывать».
 */
export function pruneTexts(texts: Record<string, unknown>): Record<string, string> {
  const result: Record<string, string> = {};
  for (const [key, value] of Object.entries(texts)) {
    const entry = BY_KEY.get(key);
    if (!entry || typeof value !== "string") continue;
    if (value === entry.default) continue;
    result[key] = value;
  }
  return result;
}
