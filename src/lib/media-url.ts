/**
 * Адрес фотографии или ролика для панели.
 *
 * Панель переехала на обычный хостинг заказчицы — там она открывается без ВПН.
 * Везти к ней заодно и все фотографии каталога незачем: это 236 МБ, которые
 * уже лежат на сайте. Поэтому при сборке панели задаётся NEXT_PUBLIC_MEDIA_BASE
 * (адрес сайта), и все снимки в панели берутся оттуда.
 *
 * Когда переменная не задана — на Vercel и в разработке — ничего не меняется:
 * файлы лежат рядом, и путь остаётся прежним.
 */
const BASE = (process.env.NEXT_PUBLIC_MEDIA_BASE || "").replace(/\/+$/, "");

export function mediaUrl(src: string | null | undefined): string {
  if (!src) return "";
  // Уже полный адрес или картинка, вшитая прямо в страницу, — не трогаем.
  if (!BASE || !src.startsWith("/") || src.startsWith("//")) return src;
  return `${BASE}${src}`;
}
