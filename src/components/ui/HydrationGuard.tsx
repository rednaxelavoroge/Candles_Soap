"use client";

import { useEffect } from "react";

/**
 * Отметка «React ожил».
 *
 * Половина блоков главной уходит в разметку с `opacity: 0` — они выезжают
 * при прокрутке. Пока скрипты не отработали, показывать нечего, и на этот
 * случай в globals.css лежит страховка: без класса `js` всё принудительно
 * видно.
 *
 * Беда была в том, что класс `js` вешала первая же строка скрипта в разметке —
 * то есть страховка снималась до того, как выяснится, доехал ли основной код.
 * В Яндекс Браузере он иногда не доезжал, и заказчица видела пустой экран.
 *
 * Теперь так: класс по-прежнему ставится сразу (иначе моргнёт), но сторож
 * в разметке снимает его, если через две с половиной секунды React не
 * отметился здесь. Не ожил — вернулась страховка.
 *
 * Отметка живёт в window, а не в атрибуте <html>: атрибутами корня
 * распоряжается React, и в разработке Fast Refresh стирал их вместе с
 * отметкой — сторож честно решал, что страница не ожила.
 */
export function HydrationGuard() {
  useEffect(() => {
    (window as Window & { __siteHydrated?: boolean }).__siteHydrated = true;
  }, []);

  return null;
}
