#!/usr/bin/env bash
#
# Собирать ли этот коммит на Vercel.
#
# Выход 0 — сборку пропустить, 1 — собирать. Так устроен «Ignored Build Step»
# у Vercel, и порядок здесь обратный привычному.
#
# Зачем. На Vercel живёт только запасной вход в панель; боевой сайт и боевая
# панель стоят на хостинге заказчицы и выкладываются своими воркфлоу. При этом
# каждый её коммит с фотографией или карточкой заставлял Vercel собирать проект
# заново — и суточный предел бесплатного тарифа (сто выкладок НА ВЕСЬ АККАУНТ)
# выедался её работой, останавливая заодно другие проекты. Так и вышло
# вечером 02.09.2026.
#
# Поэтому: правки контента Vercel пропускает, правки кода — собирает.
# Зеркало при этом отстаёт по содержимому, но панель на нём остаётся рабочей —
# она читает данные из репозитория живьём, а не из сборки.
#
# Если что-то в этой проверке пойдёт не так, она обязана ответить «собирать».
# Лишняя сборка — мелочь, а пропущенная правка кода — сломанный запасной вход.

set -u

# Пути, изменения в которых сборки не требуют. Это ровно то, что пишет панель:
# данные каталога, фотографии изделий и обложек разделов, кадры мастерской и
# портрет заказчицы. Всё прочее в public/ (шрифты, .htaccess, значки) меняем
# только мы — такие правки собираются как обычно.
CONTENT_PATHS=(
  ':(exclude)src/data'
  ':(exclude)public/catalog'
  ':(exclude)public/backstage'
  ':(exclude,glob)public/portrait-*.webp'
)

# С чем сравнивать. VERCEL_GIT_PREVIOUS_SHA — коммит последней удачной сборки;
# он вернее, чем HEAD^: если код и контент приехали одним пушем, сравнение с
# родителем показало бы только контент, и правка кода не выложилась бы никогда.
base="${VERCEL_GIT_PREVIOUS_SHA:-}"
if [ -z "$base" ] || ! git cat-file -e "${base}^{commit}" 2>/dev/null; then
  base="HEAD^"
fi
if ! git cat-file -e "${base}^{commit}" 2>/dev/null; then
  echo "Не с чем сравнивать (${base} нет в клоне) — собираем."
  exit 1
fi

if git diff --quiet "$base" HEAD -- "${CONTENT_PATHS[@]}"; then
  echo "Изменились только данные каталога и медиафайлы — сборку пропускаем."
  exit 0
fi

echo "Есть правки кода — собираем."
exit 1
